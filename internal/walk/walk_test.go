func TestRepoConfig(t *testing.T) {
	c, err := ParseConfig([]byte("hints: Migrations first.\norder:\n  - name: Migrations\n    paths: [\"packages/db/migrations/**\"]\n  - name: Chatbot tools\n    paths: [\"apps/chatbot/**/*.yaml\"]\nnoise: [\"**/*.lock.json\"]\n"))
	if err != nil {
		t.Fatal(err)
	}
	if got := c.Classify("packages/db/migrations/2026/x.ts", ""); got != "repo1" {
		t.Fatalf("migration: %s", got)
	}
	if got := c.Classify("apps/chatbot/tools/a.yaml", ""); got != "repo2" || c.LayerName("repo2") != "Chatbot tools" {
		t.Fatalf("chatbot: %s", got)
	}
	if got := c.Classify("x/y.lock.json", ""); got != "noise" {
		t.Fatalf("noise: %s", got)
	}
	// the repository's layers come before every built-in one
	if c.Rank("repo2") >= c.Rank("schema") {
		t.Fatal("repo layers must come first")
	}
}

func TestDependenciesAndOrder(t *testing.T) {
	files := []File{
		{Path: "web/src/pages/Coupons.tsx", Status: "added", Patch: "@@ -0,0 +1,2 @@\n+import { api } from '../lib/api'\n+import { Coupon } from '../types/coupon'"},
		{Path: "web/src/types/coupon.ts", Status: "added", Patch: "@@ -0,0 +1 @@\n+export interface Coupon {}"},
		{Path: "web/src/lib/api.ts", Status: "modified", Patch: "@@ -1 +1 @@\n-a\n+b"},
		{Path: "internal/api/coupons.go", Status: "added", Patch: "@@ -0,0 +1,3 @@\n+import (\n+\t\"acme/shop/internal/coupons\"\n+)"},
		{Path: "internal/coupons/service.go", Status: "added", Patch: "@@ -0,0 +1 @@\n+package coupons"},
		{Path: "internal/coupons/service_test.go", Status: "added", Patch: "@@ -0,0 +1 @@\n+package coupons"},
	}
	edges := Dependencies(files)
	has := func(from, to string) bool {
		for _, e := range edges {
			if e.From == from && e.To == to {
				return true
			}
		}
		return false
	}
	if !has("web/src/pages/Coupons.tsx", "web/src/types/coupon.ts") || !has("web/src/pages/Coupons.tsx", "web/src/lib/api.ts") {
		t.Fatalf("relative imports: %v", edges)
	}
	if !has("internal/api/coupons.go", "internal/coupons/service.go") || has("internal/api/coupons.go", "internal/coupons/service_test.go") {
		t.Fatalf("go import: %v", edges)
	}
	if !has("internal/coupons/service_test.go", "internal/coupons/service.go") {
		t.Fatalf("test after its file: %v", edges)
	}
	var c *RepoConfig
	var paths []string
	layer := map[string]string{}
	for _, f := range files {
		paths = append(paths, f.Path)
		layer[f.Path] = c.Classify(f.Path, f.Patch)
	}
	got := Order(paths, func(p string) int { return c.Rank(layer[p]) }, edges)
	pos := map[string]int{}
	for i, p := range got {
		pos[p] = i
	}
	if pos["internal/coupons/service.go"] > pos["internal/api/coupons.go"] || pos["internal/api/coupons.go"] > pos["web/src/pages/Coupons.tsx"] {
		t.Fatalf("order: %v", got)
	}
	if pos["internal/coupons/service_test.go"] != len(got)-1 {
		t.Fatalf("tests last: %v", got)
	}
}

// fakeAI answers the summary call per file and the plan with what it is given.
type fakeAI struct {
	plan  func(units []string) string
	calls int
}

func (f *fakeAI) Complete(_ context.Context, system, user string, _ bool) (string, error) {
	f.calls++
	if strings.Contains(system, "guided walkthrough") {
		var ids []string
		for _, l := range strings.Split(user, "\n") {
			if strings.HasPrefix(l, "u") && strings.Contains(l, " | ") {
				ids = append(ids, strings.SplitN(l, " ", 2)[0])
			}
		}
		return f.plan(ids), nil
	}
	type fl struct {
		Path    string `json:"path"`
		Summary string `json:"summary"`
	}
	var out struct {
		Files []fl `json:"files"`
	}
	for _, l := range strings.Split(user, "\n") {
		if strings.HasPrefix(l, "### ") {
			p := strings.SplitN(strings.TrimPrefix(l, "### "), " (", 2)[0]
			out.Files = append(out.Files, fl{p, "Changes " + p + "."})
		}
	}
	b, _ := json.Marshal(out)
	return string(b), nil
}

func sample() Input {
	f := func(p string) File {
		return File{Path: p, Status: "added", Additions: 1, Patch: "@@ -0,0 +1 @@\n+" + p}
	}
	return Input{Title: "Coupons", Files: []File{f("web/src/pages/Coupons.tsx"), f("db/migrations/1.sql"), f("internal/coupons/service.go"), f("internal/api/coupons.go"), f("go.sum")}}
}

func TestBuildCoverage(t *testing.T) {
	// the AI drops one unit, repeats one and invents one: every unit still appears exactly once
	ai := &fakeAI{plan: func(ids []string) string {
		return fmt.Sprintf(`{"overview":"o","steps":[{"title":"A","units":["%s","%s","u99"]},{"title":"B","units":["%s","%s"]}]}`, ids[0], ids[1], ids[1], ids[2])
	}}
	doc, files := Build(context.Background(), sample(), ai, nil)
	if doc.Order != "ai" {
		t.Fatalf("order %s, warnings %v", doc.Order, doc.Warnings)
	}
	seen := map[string]int{}
	for _, s := range doc.Steps {
		for _, u := range s.Units {
			seen[u.Path]++
		}
	}
	for _, f := range files {
		if f.Layer == "noise" {
			continue
		}
		if seen[f.Path] != 1 {
			t.Fatalf("%s appears %d times: %+v", f.Path, seen[f.Path], doc.Steps)
		}
	}
	if len(doc.Noise) != 1 || doc.Noise[0].Path != "go.sum" {
		t.Fatalf("noise: %+v", doc.Noise)
	}
	if doc.Steps[len(doc.Steps)-1].Title != "Everything else" {
		t.Fatalf("the left-out unit has no home: %+v", doc.Steps)
	}
	for _, f := range files {
		if f.Layer != "noise" && f.Summary != "Changes "+f.Path+"." {
			t.Fatalf("summary of %s: %q", f.Path, f.Summary)
		}
	}
}

