func TestParsePatch(t *testing.T) {
	p := "@@ -1,3 +1,4 @@ func main() {\n a\n-b\n+B\n+c\n d\n@@ -10 +11 @@\n-x\n+y\n\\ No newline at end of file"
	hs := ParsePatch(p)
	if len(hs) != 2 {
		t.Fatalf("hunks %d", len(hs))
	}
	h := hs[0]
	if h.Header != "func main() {" || h.OldStart != 1 || h.NewLines != 4 || len(h.Lines) != 5 {
		t.Fatalf("hunk 0: %+v", h)
	}
	if l := h.Lines[2]; l.T != "+" || l.N != 2 || l.S != "B" {
		t.Fatalf("line: %+v", l)
	}
	if l := h.Lines[4]; l.O != 3 || l.N != 4 {
		t.Fatalf("context numbers: %+v", l)
	}
	if hs[1].OldLines != 1 || hs[1].Lines[2].T != `\` {
		t.Fatalf("hunk 1: %+v", hs[1])
	}
	// the hash follows what changed, not where
	moved := ParsePatch("@@ -40,3 +41,4 @@\n a\n-b\n+B\n+c\n d")
	if moved[0].Hash != h.Hash {
		t.Fatal("moving a hunk changed its hash")
	}
	edited := ParsePatch("@@ -1,3 +1,4 @@\n a\n-b\n+B!\n+c\n d")
	if edited[0].Hash == h.Hash {
		t.Fatal("editing a hunk kept its hash")
	}
}

